"""Model release gate: the committed model must load, agree with its own published
results, and meet a minimum quality bar. A bad retrain or a dependency upgrade that
changes model behaviour fails here instead of in production."""

import numpy as np
from PIL import Image

from conftest import sample_path

MIN_TEST_ACCURACY = 0.95
MIN_CLASS_F1 = 0.90


def test_metrics_meet_quality_bar(metrics):
    assert metrics["test_accuracy"] >= MIN_TEST_ACCURACY
    for name in metrics["class_names"]:
        f1 = metrics["classification_report"][name]["f1-score"]
        assert f1 >= MIN_CLASS_F1, f"{name} F1 {f1:.3f} below {MIN_CLASS_F1}"


def test_class_names_consistent(app_module, metrics):
    assert app_module.get_class_names() == metrics["class_names"]


def test_model_output_shape(app_module):
    model = app_module.get_model()
    n = len(app_module.get_class_names())
    arr = np.zeros((1, app_module.IMG_SIZE, app_module.IMG_SIZE, 3), dtype=np.uint8)
    probs = np.asarray(model(arr, training=False))
    assert probs.shape == (1, n)
    assert np.isclose(probs.sum(), 1.0, atol=1e-4)


def test_model_reproduces_published_sample_predictions(app_module, samples):
    """The dashboard's sample gallery was generated by this model; re-running the
    model on those images must give the same labels and confidences."""
    model = app_module.get_model()
    class_names = app_module.get_class_names()
    mismatches = []
    for s in samples:
        img = Image.open(sample_path(s["file"])).convert("RGB")
        img = img.resize((app_module.IMG_SIZE, app_module.IMG_SIZE))
        arr = np.array(img, dtype=np.uint8)[None, ...]
        probs = np.asarray(model(arr, training=False))[0]
        predicted = class_names[int(np.argmax(probs))]
        confidence = float(np.max(probs))
        # Label AND confidence: the gallery must show what classifying that exact
        # picture gives (samples.json stores confidence rounded to 4 decimals).
        if predicted != s["predicted"] or abs(confidence - s["confidence"]) > 1e-4:
            mismatches.append((s["file"], s["predicted"], s["confidence"], predicted, confidence))
    assert not mismatches, f"prediction drift: {mismatches}"
